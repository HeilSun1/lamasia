function Publish-SiteStatus {
  param(
    [string]$Root,
    [string]$RunId,
    [string]$StartedUtc,
    [string]$FinishedUtc,
    [string]$LastSuccessUtc,
    [string]$Source = 'local',
    [string]$Status = 'ok',
    [int]$ExitCode = 0,
    [int]$ConsecutiveFailures = 0,
    [bool]$Blocked = $false,
    [string]$BlockedSinceUtc = $null,
    [string[]]$BlockedCodes = @(),
    [string[]]$FailedScripts = @(),
    [string[]]$StaleCaches = @(),
    [string[]]$Healed = @(),
    [int]$StaleHours = 36,
    [int]$HardStaleHours = 72
  )
  $obj = [ordered]@{
    schema              = 1
    runId               = $RunId
    runStartedUtc       = $StartedUtc
    runFinishedUtc      = $FinishedUtc
    lastSuccessUtc      = $LastSuccessUtc
    lastRunSource       = $Source
    lastRunStatus       = $Status
    exitCode            = $ExitCode
    consecutiveFailures = $ConsecutiveFailures
    blocked             = $Blocked
    # ConvertTo-Json 会把 $null 写成空串，这里统一成真正的 null，免得前端拿到 "" 还要额外判断
    blockedSinceUtc     = $(if ($BlockedSinceUtc) { $BlockedSinceUtc } else { $null })
    blockedCodes        = @($BlockedCodes)
    failedScripts       = @($FailedScripts)
    staleCaches         = @($StaleCaches)
    healed              = @($Healed)
    staleHours          = $StaleHours
    hardStaleHours      = $HardStaleHours
  }
  Write-JsonFile (Join-Path $Root 'assets\data\status.json') $obj
}
